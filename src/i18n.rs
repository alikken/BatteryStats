/// Перевод «системных» имён процессов.
pub fn pretty_process(key: &str) -> Option<&'static str> {
    match key {
        "System" => Some(t().p_system),
        "Memory Compression" => Some(t().p_memcomp),
        "Registry" => Some(t().p_registry),
        _ => None,
    }
}
