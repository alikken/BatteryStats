//! Локализация: English, Русский, Polski.
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    En,
    Ru,
    Pl,
}

static LANG: AtomicU8 = AtomicU8::new(0);

pub fn lang() -> Lang {
    match LANG.load(Ordering::Relaxed) {
        1 => Lang::Ru,
        2 => Lang::Pl,
        _ => Lang::En,
    }
}

pub fn set_lang(l: Lang) {
    LANG.store(
        match l {
            Lang::En => 0,
            Lang::Ru => 1,
            Lang::Pl => 2,
        },
        Ordering::Relaxed,
    );
}

/// Язык интерфейса Windows → наш язык.
pub fn detect() -> Lang {
    let id = unsafe { windows_sys::Win32::Globalization::GetUserDefaultUILanguage() };
    match id & 0x3FF {
        0x19 | 0x3F | 0x23 | 0x40 => Lang::Ru, // русский, казахский, белорусский, киргизский
        0x15 => Lang::Pl,
        _ => Lang::En,
    }
}

pub fn code(l: Lang) -> &'static str {
    match l {
        Lang::En => "en",
        Lang::Ru => "ru",
        Lang::Pl => "pl",
    }
}

/// Подставляет аргументы вместо `{}` по порядку.
pub fn fill(tpl: &str, args: &[&str]) -> String {
    let mut out = String::with_capacity(tpl.len() + 16);
    let mut it = args.iter();
    let mut rest = tpl;
    while let Some(i) = rest.find("{}") {
        out.push_str(&rest[..i]);
        out.push_str(it.next().copied().unwrap_or(""));
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

